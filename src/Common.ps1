Set-StrictMode -Version Latest

function Test-TailnetIPv4([string]$Address) {
    $parsed = $null
    if (![Net.IPAddress]::TryParse($Address, [ref]$parsed)) { return $false }
    $b = $parsed.GetAddressBytes()
    return ($b.Length -eq 4 -and $b[0] -eq 100 -and $b[1] -ge 64 -and $b[1] -le 127)
}

function Set-ListenerAcl([string]$Path, [switch]$UsersRead) {
    # SIDs work on localized Windows installations.
    $acl = New-Object Security.AccessControl.DirectorySecurity
    if (!(Get-Item -LiteralPath $Path).PSIsContainer) { $acl = New-Object Security.AccessControl.FileSecurity }
    $acl.SetAccessRuleProtection($true, $false)
    $acl.SetOwner((New-Object Security.Principal.SecurityIdentifier('S-1-5-32-544')))
    foreach ($sid in @('S-1-5-18', 'S-1-5-32-544')) {
        $identity = New-Object Security.Principal.SecurityIdentifier($sid)
        if ($acl -is [Security.AccessControl.DirectorySecurity]) {
            $rule = New-Object Security.AccessControl.FileSystemAccessRule($identity, 'FullControl', 'ContainerInherit,ObjectInherit', 'None', 'Allow')
        } else { $rule = New-Object Security.AccessControl.FileSystemAccessRule($identity, 'FullControl', 'Allow') }
        $acl.AddAccessRule($rule)
    }
    if ($UsersRead) {
        $identity = New-Object Security.Principal.SecurityIdentifier('S-1-5-32-545')
        if ($acl -is [Security.AccessControl.DirectorySecurity]) {
            $rule = New-Object Security.AccessControl.FileSystemAccessRule($identity, 'ReadAndExecute', 'ContainerInherit,ObjectInherit', 'None', 'Allow')
        } else { $rule = New-Object Security.AccessControl.FileSystemAccessRule($identity, 'ReadAndExecute', 'Allow') }
        $acl.AddAccessRule($rule)
    }
    Set-Acl -LiteralPath $Path -AclObject $acl
}

function New-ListenerConfig([string]$Root, [string]$UserName, [string]$ListenAddress, [int]$Port, [string[]]$AllowedClientAddress) {
    $dir = $Root.Replace('\', '/')
    $sftp = (Join-Path $env:WINDIR 'System32/OpenSSH/sftp-server.exe').Replace('\', '/')
    $allowed = ($AllowedClientAddress | ForEach-Object { $UserName.ToLowerInvariant() + '@' + $_ }) -join ' '
    return @"
# Generated by SSH-listener. This is separate from the Windows service config.
Port $Port
ListenAddress $ListenAddress
HostKey "$dir/keys/ssh_host_ed25519_key"
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
AuthenticationMethods publickey
PermitEmptyPasswords no
AllowUsers $allowed
AuthorizedKeysFile "$dir/authorized_keys"
AllowTcpForwarding no
AllowAgentForwarding no
LoginGraceTime 30
MaxAuthTries 3
LogLevel VERBOSE
Subsystem sftp "$sftp"
"@
}
